/* Generate from the actual Studio sources, never maintain a parallel price list. */
const fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.resolve(__dirname,'..');
function generate(){
 const sandbox={Bess:require('../assets/js/bess.js'),AdditionalSystems:require('../assets/js/additional-systems.js')};sandbox.self=sandbox;
 vm.runInNewContext(fs.readFileSync(path.join(root,'assets/js/state.js'),'utf8'),sandbox);
 const app=fs.readFileSync(path.join(root,'assets/js/app.js'),'utf8');
 const presets=vm.runInNewContext('('+app.match(/const PRESETS = (\{[\s\S]*?\n    \});/)[1]+')');
 const presetReset=vm.runInNewContext('('+app.match(/const resetDesign = (\{[\s\S]*?\n        \});/)[1]+')');
 const {CONTENT}=require('../assets/js/content.js');
 const defaults=Object.fromEntries(Object.entries(sandbox.StateStore.DEFAULTS).filter(([k])=>!/^cust[A-Z]|^prop|^prep|Url$/.test(k)));
 return '// Generated by scripts/build-assistant-knowledge.cjs from state.js, app.js and content.js.\nexport default '+JSON.stringify({sources:['assets/js/state.js','assets/js/app.js: PRESETS / resetDesign','assets/js/content.js','assets/js/finance.js'],defaults,presets,presetReset,content:CONTENT},null,2)+';\n';
}
if(require.main===module)fs.writeFileSync(path.join(root,'platform/studio-knowledge.mjs'),generate());
module.exports={generate};
