'use strict';
// Isolated browser QA. Never points at a production origin.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const XLSX = require('./vendor/xlsx.mini.min.js');
const resolveDep = name => require.resolve(name, {paths:[path.resolve(__dirname,'../qa'), __dirname]});
const { chromium: pw } = require(resolveDep('playwright'));
const origin = process.env.CONCEPT_TEST_ORIGIN || 'http://127.0.0.1:8080';
const host = new URL(origin).hostname;
assert(['127.0.0.1','localhost'].includes(host), 'QA is local-only; do not use production');
const output = process.env.CONCEPT_TEST_OUTPUT || '/tmp/qs-concept-evidence';
fs.mkdirSync(output, {recursive:true});
const pages = ['scope','revisions','customer','survey','followups','export'];
let assertions = 0;
const check=(condition,label)=>{assert(condition,label);assertions++;};
(async()=>{
  const chromium = (await import(pathToFileURL(resolveDep('@sparticuz/chromium')).href)).default;
  const browser = await pw.launch({executablePath:await chromium.executablePath(),args:chromium.args.filter(x=>x!=='--single-process'),headless:true});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
    const errors=[],api=[],external=[];
    await context.addInitScript(()=>{window.__storageAccess=[];for(const method of ['getItem','setItem','removeItem','clear']){const original=Storage.prototype[method];Storage.prototype[method]=function(...args){window.__storageAccess.push(method);return original.apply(this,args);};}});
    const page=await context.newPage();
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
    context.on('request',r=>{const url=new URL(r.url());if(url.pathname.startsWith('/api/'))api.push(r.url());if(!['127.0.0.1','localhost'].includes(url.hostname)&&url.protocol!=='blob:')external.push(r.url());});
    await page.goto(origin+'/concept-preview/');
    await page.locator('#view h2').first().waitFor();
    check((await page.title()).includes('concept preview'),'concept title');
    for(const view of pages){await page.locator(`[data-view="${view}"]`).click();await page.screenshot({path:path.join(output,view+'-desktop.png'),fullPage:true});check(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)),view+' desktop has no overflow');}
    await page.locator('[data-view="scope"]').click();
    await page.locator('[data-requested="water"]').check();
    check(await page.locator('.inline-alert').count()===1,'requested unpriced scope adds cover warning');
    check((await page.locator('.offer-card').innerText()).includes('1 requested scope price pending'),'pending not zero');
    await page.locator('#mode-roof').selectOption('included');
    check((await page.locator('.offer-card').innerText()).includes('No priced items'),'included scope not double counted');
    await page.locator('#publishSample').click();
    check((await page.locator('#conceptToast').innerText()).includes('Confirm that included scope'),'publishing blocked before inclusion acknowledgement');
    await page.locator('[data-confirm="roof"]').check();
    await page.locator('#publishSample').click();
    check((await page.locator('#ribbonRevision').innerText()).includes('R3'),'sample revision published');
    await page.locator('[data-view="customer"]').click();
    check((await page.locator('.customer-bar').innerText()).includes('Revision 1'),'old customer view stays pinned');
    check((await page.locator('.customer-values').innerText()).includes('5,20,000'),'old solar snapshot unchanged');
    await page.locator('input[value="changes"]').check();
    await page.locator('#responseName').fill('Demo <img src=x onerror=alert(1)>');
    await page.locator('#responseComment').fill('Please review the scope <script>bad()</script>');
    await page.locator('#responseConsent').check();
    await page.locator('#responseForm button[type="submit"]').click();
    check((await page.locator('.response-success').innerText()).includes('Revision 1'),'response bound to R1');
    check((await page.locator('.timeline').innerText()).includes('latest not approved'),'old response not latest approval');
    check(await page.locator('.timeline script,.timeline img,.response-success img').count()===0,'customer input escaped');
    await page.locator('#viewLatest').click();
    check((await page.locator('.customer-bar').innerText()).includes('Revision 3'),'explicit latest navigation');
    check(await page.locator('#responseForm').count()===1,'new revision requires fresh response');
    check((await page.locator('.customer-values').innerText()).includes('5,40,000'),'latest snapshot preserves solar value');
    check((await page.locator('.customer-values').innerText()).includes('No priced items'),'included scope not extra charge');
    await page.locator('#responseFollowup').click();
    check((await page.locator('#taskForm input[name="title"]').inputValue()).includes('Revision 1'),'response followup has version context');
    await page.locator('#taskForm button[type="submit"]').click();
    check((await page.locator('.mini-metric strong').first().innerText())==='3','followup task added');
    await page.locator('[data-task="1"]').click();
    check((await page.locator('.mini-metric strong').first().innerText())==='2','task completion works');
    await page.locator('[data-filter="done"]').click();
    check(await page.locator('.task-row').count()===2,'completed filter works');
    await page.locator('[data-view="survey"]').click();
    await page.locator('[name="source"]').selectOption('Site-measured');
    await page.locator('[name="area"]').fill('132');
    await page.locator('#surveyForm button[type="submit"]').click();
    check((await page.locator('.checklist-row').first().innerText()).includes('132 m² · Site-measured'),'survey source saved locally');
    await page.locator('[data-view="export"]').click();
    const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#downloadExcel').click()]);
    check(download.suggestedFilename()==='DEMO-026_R3_Customer.xlsx','actual xlsx download with correct revision');
    const bytes=fs.readFileSync(await download.path()),wb=XLSX.read(bytes,{type:'buffer'}),rows=XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]],{header:1});
    check(wb.SheetNames.length===1,'no hidden internal worksheets');
    check(rows.find(r=>r[0]==='Revision')[1]===3,'xlsx revision value');
    check(rows.find(r=>r[0].startsWith('Solar EPC'))[1]===540000,'xlsx solar price is numeric snapshot');
    check(rows.some(r=>r[0].startsWith('Leak Proof')&&r[1]==='Included in entered Solar EPC price'),'xlsx inclusion reflected');
    check(rows.some(r=>r[0].startsWith('Rainwater')&&r[1]==='To be confirmed'),'xlsx missing price not zero');
    check(!Object.values(wb.Sheets[wb.SheetNames[0]]).some(x=>x&&x.f),'xlsx values only, no formulas');
    check(!JSON.stringify(rows).match(/staffNotes|internalNotes|purchase cost|internal margin/i),'no private fields exported');
    await page.locator('#resetDemo').click();await page.locator('#cancelReset').click();
    check(await page.locator('#resetDialog').isVisible()===false,'reset can cancel');
    await page.reload();await page.locator('#downloadExcel').waitFor();
    check((await page.locator('.export-toolbar').innerText()).includes('R2'),'reload discards sample changes');
    check((await page.evaluate(()=>window.__storageAccess.length))===0,'no existing storage read or written');
    await page.locator('#resetDemo').click();await page.locator('#confirmReset').click();
    check(await page.locator('#viewTitle').innerText()==='Scope & pricing','reset returns to scope');
    for(const width of [390,768]){
      await page.setViewportSize({width,height:900});
      for(const view of pages){await page.locator(`[data-view="${view}"]`).click();check(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)),`${view} at ${width}px has no horizontal page overflow`);if(width===390)await page.screenshot({path:path.join(output,view+'-mobile.png'),fullPage:true});}
    }
    check(api.length===0,'zero API requests');check(external.length===0,'zero external requests');check(errors.length===0,'zero JS/CSP console errors: '+errors.join(';'));
    await context.close();
    console.log(`PASS: ${assertions} checks; six screens at desktop/tablet/mobile; real XLSX parsed; no API, external requests, storage access or JS/CSP errors.`);
    console.log('Screenshots: '+output);
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
